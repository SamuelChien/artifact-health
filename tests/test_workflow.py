import copy
import json
import tempfile
import unittest
from pathlib import Path

from scripts.measure import measure
from scripts.evidence import digest_file
from scripts.workflow import RUBRIC, grade_workflows, compare_workflows, read_workflow
from scripts.content_signals import origin_signals, invalid_reference


class WorkflowTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.base = Path(self.temp.name)
        self.source = self.base / "source"
        self.source.mkdir()
        for name, text in {"input.txt": "Fixture source 2 units at 10.", "analysis.txt": "Fixture: 2 times 10 equals 20.",
                           "output.txt": "Fixture total 20; unknown approval.", "review.txt": "Fixture independent arithmetic check."}.items():
            (self.source / name).write_text(text)
        self.run = self.base / "measurement"
        measure(self.source, self.run)
        self.measurement = json.loads((self.run / "measurement.json").read_text())
        self.receipt = json.loads((self.run / "run.json").read_text())
        self.ev = {p.name: {"path": p.name, "sha256": digest_file(p), "locator": "complete synthetic fixture",
                   "mode": "visual", "units": {"kind": "file", "ranges": [[1, 1]]}} for p in self.source.iterdir()}
        self.protocol = {"schema": "workflow-readiness@1", "cohort_id": "fixture", "selection": "synthetic testing only",
                         "cases": [{"id": "case", "title": "Fixture", "kind": "reconstructed_analysis", "business_case": "fixture",
                         "outcome": "total", "role": "fixture reviewer", "value": "fixture arithmetic", "acceptance": "20",
                         "inputs": [self.ev["input.txt"]], "input_document_ids": {"input.txt": "fixture-input"},
                         "required_stages": ["source", "analysis", "output", "review"]}]}
        self.protocol_path = self.base / "protocol.json"
        self.protocol_path.write_text(json.dumps(self.protocol))
        checks = {key: {"state": "met", "reason": "Synthetic fixture assertion; no real review claimed.", "evidence": [self.ev["output.txt"]]}
                  for dim in json.loads(RUBRIC.read_text())["dimensions"].values() for key in dim["checks"]}
        checks["input_origin"] = {"state": "unknown", "reason": "No authenticated original origin", "evidence": []}
        nodes = [{"id": name, "stage": stage, "evidence": [self.ev[name]]}
                 for name, stage in zip(["input.txt", "analysis.txt", "output.txt", "review.txt"], ["source", "analysis", "output", "review"])]
        edges = [{"from": a, "to": b, "kind": "derived_from", "basis": "Fixture arithmetic", "evidence": [self.ev[b]]}
                 for a,b in zip(["input.txt", "analysis.txt", "output.txt"], ["analysis.txt", "output.txt", "review.txt"])]
        self.review = {"protocol_sha256": digest_file(self.protocol_path), "measurement_run_id": self.receipt["run_id"],
                       "inventory_sha256": self.measurement["inventory_sha256"],
                       "reviewer": {"id": "independent-fixture", "kind": "agent", "model": "fixture", "protocol": "fixture-1"},
                       "cases": [{"id": "case", "author_id": "fixture-author", "outputs": [self.ev["output.txt"]],
                           "checks": checks, "nodes": nodes, "edges": edges, "validation": {"passed": True, "method": "fixture arithmetic",
                           "reviewer_id": "independent-fixture", "evidence": [self.ev["output.txt"]]}}]}

    def tearDown(self):
        self.temp.cleanup()

    def grade(self, name="grade"):
        p = self.base / "review.json"
        p.write_text(json.dumps(self.review))
        return grade_workflows(self.run, self.protocol_path, p, self.base / name)

    def test_unknown_origin_is_not_a_human_verdict(self):
        self.assertEqual(origin_signals("Ordinary wording")['authorship_verdict'], "unknown")
        self.assertEqual(origin_signals("AI-generated by fixture")['declaration_count'], 1)
        grade = self.grade()
        self.assertEqual(grade["points"], 95)
        self.assertEqual(grade["unknown_points"], 5)
        self.assertEqual(grade["counts"]["validated_tasks"], 1)
        self.assertEqual(grade["counts"]["historical_employee_tasks"], 0)

    def test_error_string_literals_are_not_broken_references(self):
        self.assertFalse(invalid_reference('IF(A1="#REF!",1,0)'))
        self.assertFalse(invalid_reference("'#REF!'!A1"))
        self.assertTrue(invalid_reference('IFERROR(C11/#REF!, "NA")'))

    def test_missing_author_does_not_establish_independence(self):
        del self.review["cases"][0]["author_id"]
        with self.assertRaisesRegex(ValueError, "author identity"):
            self.grade()

    def test_identical_bytes_cannot_be_an_output(self):
        self.review["cases"][0]["outputs"] = [self.ev["input.txt"]]
        with self.assertRaisesRegex(ValueError, "overlap"):
            self.grade()

    def test_independence_cannot_be_self_review(self):
        self.review["cases"][0]["author_id"] = "independent-fixture"
        with self.assertRaisesRegex(ValueError, "independent"):
            self.grade()

    def test_orphan_stage_cannot_establish_completeness(self):
        self.review["cases"][0]["edges"] = [self.review["cases"][0]["edges"][0]]
        with self.assertRaises(ValueError):
            self.grade()

    def test_disconnected_extra_output_cannot_be_hidden(self):
        self.review["cases"][0]["outputs"].append(self.ev["review.txt"])
        with self.assertRaisesRegex(ValueError, "reach output"):
            self.grade()

    def test_future_input_blocks_historical_task(self):
        self.protocol["cases"][0].update(kind="historical_employee_task", temporal_cutoff="2020-01-01T00:00:00+00:00")
        self.protocol["cases"][0]["inputs"][0]["available_at"] = "2021-01-01T00:00:00+00:00"
        self.protocol_path.write_text(json.dumps(self.protocol))
        self.review["protocol_sha256"] = digest_file(self.protocol_path)
        with self.assertRaisesRegex(ValueError, "unavailable at"):
            self.grade()

    def test_relabeling_same_inputs_cannot_multiply_tasks(self):
        case = copy.deepcopy(self.protocol["cases"][0]);case.update(id="other", outcome="reworded")
        self.protocol["cases"].append(case)
        self.protocol_path.write_text(json.dumps(self.protocol))
        self.review["protocol_sha256"] = digest_file(self.protocol_path)
        other = copy.deepcopy(self.review["cases"][0]);other['id'] = "other";self.review["cases"].append(other)
        with self.assertRaisesRegex(ValueError, "canonical input"):
            self.grade()

    def test_tampered_report_is_rejected(self):
        self.grade()
        (self.base / "grade/workflow.json").write_text('{}')
        with self.assertRaisesRegex(ValueError, "changed"):
            read_workflow(self.base / "grade")

    def test_changed_reviewer_blocks_comparison_and_negative_delta_is_retained(self):
        self.grade("before")
        self.review["cases"][0]["checks"]["dependencies"]["state"] = "failed"
        self.grade("after")
        result = compare_workflows(self.base / "before", self.base / "after")
        self.assertEqual(result["points_delta"], -7.5)
        self.review["reviewer"]["protocol"] = "different"
        self.grade("changed")
        self.assertFalse(compare_workflows(self.base / "before", self.base / "changed")["comparable"])

    def test_declared_origin_needs_more_than_metadata(self):
        self.review["cases"][0]["checks"]["input_origin"] = {"state": "met", "reason": "Creator says Microsoft", "evidence": [self.ev["input.txt"]]}
        with self.assertRaisesRegex(ValueError, "metadata/style"):
            self.grade()
